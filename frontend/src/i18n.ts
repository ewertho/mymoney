const dictionaries = { "pt-BR": pt, "en-US": en };

/** i18n mínimo: chave com ponto ("cat.food") e interpolação {{var}}. */
export function useTranslation() {
  const dictionary = dictionaries[useStore((s) => s.language)];
  const t = (key: string, vars: Record<string, string | number> = {}) => {
    const text = key.split(".").reduce<unknown>((node, part) => (node as Record<string, unknown>)?.[part], dictionary);
    return String(text ?? key).replace(/{{(\w+)}}/g, (_, name) => String(vars[name] ?? ""));
  };
  return { t };
}